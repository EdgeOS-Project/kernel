static uint8_t aes_multiply(uint8_t left, uint8_t right) {
    uint8_t result = 0;
    while (right) {
        if (right & 1u) result ^= left;
        left = (uint8_t)((left << 1) ^ ((left & 0x80u) ? 0x1bu : 0u));
        right >>= 1;
    }
    return result;
}

static void aes_add_round_key(uint8_t state[16], const uint8_t *key) {
    for (uint32_t index = 0; index < 16u; ++index) state[index] ^= key[index];
}

static void aes_shift_rows(uint8_t state[16]) {
    uint8_t copy[16];
    memcpy(copy, state, sizeof(copy));
    for (uint32_t row = 0; row < 4u; ++row)
        for (uint32_t column = 0; column < 4u; ++column)
            state[row + 4u * column] =
                copy[row + 4u * ((column + row) & 3u)];
}

static void aes_inverse_shift_rows(uint8_t state[16]) {
    uint8_t copy[16];
    memcpy(copy, state, sizeof(copy));
    for (uint32_t row = 0; row < 4u; ++row)
        for (uint32_t column = 0; column < 4u; ++column)
            state[row + 4u * column] =
                copy[row + 4u * ((column + 4u - row) & 3u)];
}

static void aes_mix_columns(uint8_t state[16]) {
    for (uint32_t column = 0; column < 4u; ++column) {
        uint8_t *p = state + column * 4u;
        uint8_t a = p[0], b = p[1], c = p[2], d = p[3];
        p[0] = aes_multiply(a, 2u) ^ aes_multiply(b, 3u) ^ c ^ d;
        p[1] = a ^ aes_multiply(b, 2u) ^ aes_multiply(c, 3u) ^ d;
        p[2] = a ^ b ^ aes_multiply(c, 2u) ^ aes_multiply(d, 3u);
        p[3] = aes_multiply(a, 3u) ^ b ^ c ^ aes_multiply(d, 2u);
    }
}

static void aes_inverse_mix_columns(uint8_t state[16]) {
    for (uint32_t column = 0; column < 4u; ++column) {
        uint8_t *p = state + column * 4u;
        uint8_t a = p[0], b = p[1], c = p[2], d = p[3];
        p[0] = aes_multiply(a, 14u) ^ aes_multiply(b, 11u) ^
               aes_multiply(c, 13u) ^ aes_multiply(d, 9u);
        p[1] = aes_multiply(a, 9u) ^ aes_multiply(b, 14u) ^
               aes_multiply(c, 11u) ^ aes_multiply(d, 13u);
        p[2] = aes_multiply(a, 13u) ^ aes_multiply(b, 9u) ^
               aes_multiply(c, 14u) ^ aes_multiply(d, 11u);
        p[3] = aes_multiply(a, 11u) ^ aes_multiply(b, 13u) ^
               aes_multiply(c, 9u) ^ aes_multiply(d, 14u);
    }
}

int edge_aes_initialize(edge_aes_context_t *context,
                        const uint8_t *key, uint32_t key_bytes) {
    uint32_t words;
    uint32_t total_words;
    uint8_t rcon = 1u;

    if (!context || !key || (key_bytes != 16u && key_bytes != 32u)) return -1;
    memset(context, 0, sizeof(*context));
    context->rounds = key_bytes == 16u ? 10u : 14u;
    memcpy(context->round_key, key, key_bytes);
    words = key_bytes / 4u;
    total_words = 4u * ((uint32_t)context->rounds + 1u);
    for (uint32_t word = words; word < total_words; ++word) {
        uint8_t temporary[4];
        uint8_t *output = context->round_key + word * 4u;
        const uint8_t *previous = output - 4u;
        const uint8_t *prior_round = output - words * 4u;
        memcpy(temporary, previous, sizeof(temporary));
        if (word % words == 0u) {
            uint8_t first = temporary[0];
            temporary[0] = g_aes_sbox[temporary[1]] ^ rcon;
            temporary[1] = g_aes_sbox[temporary[2]];
            temporary[2] = g_aes_sbox[temporary[3]];
            temporary[3] = g_aes_sbox[first];
            rcon = aes_multiply(rcon, 2u);
        } else if (words == 8u && word % words == 4u) {
            for (uint32_t index = 0; index < 4u; ++index)
                temporary[index] = g_aes_sbox[temporary[index]];
        }
        for (uint32_t index = 0; index < 4u; ++index)
            output[index] = prior_round[index] ^ temporary[index];
    }
    return 0;
}

void edge_aes_encrypt_block(const edge_aes_context_t *context,
                            const uint8_t input[16], uint8_t output[16]) {
    uint8_t state[16];
    if (!context || !input || !output) return;
    memcpy(state, input, sizeof(state));
    aes_add_round_key(state, context->round_key);
    for (uint32_t round = 1u; round < context->rounds; ++round) {
        for (uint32_t index = 0; index < 16u; ++index)
            state[index] = g_aes_sbox[state[index]];
        aes_shift_rows(state);
        aes_mix_columns(state);
        aes_add_round_key(state, context->round_key + round * 16u);
    }
    for (uint32_t index = 0; index < 16u; ++index)
        state[index] = g_aes_sbox[state[index]];
    aes_shift_rows(state);
    aes_add_round_key(state,
                      context->round_key + context->rounds * 16u);
    memcpy(output, state, sizeof(state));
}

void edge_aes_decrypt_block(const edge_aes_context_t *context,
                            const uint8_t input[16], uint8_t output[16]) {
    uint8_t state[16];
    if (!context || !input || !output) return;
    memcpy(state, input, sizeof(state));
    aes_add_round_key(state,
                      context->round_key + context->rounds * 16u);
    for (uint32_t round = context->rounds; round > 1u; --round) {
        aes_inverse_shift_rows(state);
        for (uint32_t index = 0; index < 16u; ++index)
            state[index] = g_aes_inverse_sbox[state[index]];
        aes_add_round_key(state, context->round_key + (round - 1u) * 16u);
        aes_inverse_mix_columns(state);
    }
    aes_inverse_shift_rows(state);
    for (uint32_t index = 0; index < 16u; ++index)
        state[index] = g_aes_inverse_sbox[state[index]];
    aes_add_round_key(state, context->round_key);
    memcpy(output, state, sizeof(state));
}
