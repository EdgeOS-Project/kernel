#include <assert.h>
#include <stdint.h>
#include <stdio.h>
#include <string.h>

#include "kernel/sha1_runtime.h"
#include "kernel/sha256_runtime.h"
#include "kernel/sha512_runtime.h"

static void test_sha1(void) {
    static const uint8_t expected[20] = {
        0xa9, 0x99, 0x3e, 0x36, 0x47, 0x06, 0x81, 0x6a,
        0xba, 0x3e, 0x25, 0x71, 0x78, 0x50, 0xc2, 0x6c,
        0x9c, 0xd0, 0xd8, 0x9d,
    };
    kernel_sha1_context_t context;
    uint8_t digest[20];

    kernel_sha1_init(&context);
    kernel_sha1_update(&context, "a", 1u);
    kernel_sha1_update(&context, "bc", 2u);
    kernel_sha1_final(&context, digest);
    assert(memcmp(digest, expected, sizeof(expected)) == 0);
}

