/* Known-answer tests for the shared AES block transform. */

#include <assert.h>
#include <stdint.h>
#include <stdio.h>
#include <string.h>

#include "lib/aes.h"

static void test_vector(const uint8_t *key, uint32_t key_bytes,
                        const uint8_t plaintext[16],
                        const uint8_t ciphertext[16]) {
    edge_aes_context_t context;
    uint8_t output[16];
    assert(edge_aes_initialize(&context, key, key_bytes) == 0);
    edge_aes_encrypt_block(&context, plaintext, output);
    assert(memcmp(output, ciphertext, 16u) == 0);
    edge_aes_decrypt_block(&context, ciphertext, output);
    assert(memcmp(output, plaintext, 16u) == 0);
}

int main(void) {
    static const uint8_t plaintext[16] = {
        0x00,0x11,0x22,0x33,0x44,0x55,0x66,0x77,
        0x88,0x99,0xaa,0xbb,0xcc,0xdd,0xee,0xff
    };
    static const uint8_t key128[16] = {
        0x00,0x01,0x02,0x03,0x04,0x05,0x06,0x07,
        0x08,0x09,0x0a,0x0b,0x0c,0x0d,0x0e,0x0f
    };
    static const uint8_t cipher128[16] = {
        0x69,0xc4,0xe0,0xd8,0x6a,0x7b,0x04,0x30,
        0xd8,0xcd,0xb7,0x80,0x70,0xb4,0xc5,0x5a
    };
    static const uint8_t key256[32] = {
        0x00,0x01,0x02,0x03,0x04,0x05,0x06,0x07,
        0x08,0x09,0x0a,0x0b,0x0c,0x0d,0x0e,0x0f,
        0x10,0x11,0x12,0x13,0x14,0x15,0x16,0x17,
        0x18,0x19,0x1a,0x1b,0x1c,0x1d,0x1e,0x1f
    };
    static const uint8_t cipher256[16] = {
        0x8e,0xa2,0xb7,0xca,0x51,0x67,0x45,0xbf,
        0xea,0xfc,0x49,0x90,0x4b,0x49,0x60,0x89
    };

    test_vector(key128, sizeof(key128), plaintext, cipher128);
    test_vector(key256, sizeof(key256), plaintext, cipher256);
    puts("aes_unit: PASS");
    return 0;
}
